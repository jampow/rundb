pub fn print_help() {
    println!("Usage: rundb --file <path> [options]");
    println!("       rundb connection <add|list|remove|test>");
    println!();
    println!("Executa um script de banco de dados (SQL Server) contra um ambiente.");
    println!("O script deve exportar {{ database, mode, params, queries }}.");
    println!();
    println!("Variáveis de ambiente esperadas:");
    println!("  DB_<ENV>_<SYSTEM>_SVR");
    println!("  DB_<ENV>_<SYSTEM>_USR");
    println!("  DB_<ENV>_<SYSTEM>_PWD");
    println!("  DB_<ENV>_<SYSTEM>_DB   (opcional)");
    println!();
    println!("Diretório de scripts:");
    println!("  Por padrão, procura em ./db-scripts (relativo ao diretório atual).");
    println!("  Pode ser sobrescrito com --scripts-dir <path> ou a env var DB_SCRIPTS_DIR.");
    println!();
    println!("Conexões armazenadas:");
    println!("  rundb connection add");
    println!("  rundb connection list");
    println!("  rundb connection test <name>");
    println!("  rundb connection remove <name>");
    println!("  São armazenadas criptografadas junto dos scripts.");
    println!();
    println!("Options:");
    println!("  --file, -f  Caminho do arquivo de script (.js)");
    println!("  --env, -e  Ambiente: dev | stg | prd (default: dev)");
    println!("  --param, -p  Parâmetro no formato chave=valor (pode repetir)");
    println!("  --json, -j  Exibe resultados em JSON puro");
    println!("  --debug, -d  Exibe SQL e resultado de todas as queries, não só a última");
    println!("  --help, -h  Mostra esta mensagem");
    println!();
    println!("Exemplos:");
    println!("  rundb --file db-scripts/find-user.js");
    println!("  rundb --file db-scripts/find-user.js --env stg");
    println!("  rundb --file db-scripts/find-user.js --param email=foo@bar.com --json");
    println!("  rundb --file db-scripts/find-user.js --debug");
    println!();
    println!("Formato do campo \"prompt\" em uma query (modo sequential):");
    println!();
    println!("  {{");
    println!("    name: 'Listar usuários',");
    println!("    sql: (p) => `SELECT Id, Email FROM [User] WHERE ...`,");
    println!("    prompt: {{");
    println!("      message:    'Qual usuário?',  // texto do prompt");
    println!("      valueField: 'Id',             // campo usado como valor");
    println!("      labelField: 'Email',          // campo exibido como label");
    println!("      paramName:  'userId',         // chave injetada em params");
    println!("      multiple:   false,             // true → checkbox (array)");
    println!("    }},");
    println!("  }},");
    println!();
    println!("Sem --debug, apenas o resultado da última query é exibido.");
    println!("Com --debug, o resultado de todas as queries é exibido durante a execução.");
}
